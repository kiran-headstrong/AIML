#: System prompt instructing the model to return strict JSON and preserve facts.
_SYSTEM_PROMPT = (
    "You are an expert resume coach who tailors resumes to specific job "
    "descriptions. You NEVER invent experience, qualifications, employers, "
    "dates, or credentials the candidate does not already have. You only "
    "suggest rephrasing, reordering, and keyword optimisation of existing "
    "content. You respond ONLY with valid JSON."
)

#: User prompt template. ``{jd_block}``, ``{resume_block}`` and ``{match_block}``
#: are substituted with the relevant context.
_PROMPT_TEMPLATE = """\
Given a candidate's resume, a target job description, and the computed match
breakdown, produce a list of specific, actionable edit suggestions that would
improve the resume's alignment with the job description.

STRICT RULES:
- Do NOT fabricate skills, experience, employers, dates, or credentials.
- Only suggest rephrasing existing content, reordering/emphasising sections,
  and incorporating relevant keywords the candidate can honestly claim.
- "skills_to_add" may only propose skills the candidate plausibly already has
  based on their resume (e.g. an umbrella term for listed tools); do not invent
  unrelated technologies.

For each suggestion provide:
- "category": EXACTLY one of ["skills_to_add", "experience_rephrase",
  "keywords_to_include", "sections_reorder"].
- "description": a concise, actionable explanation of the change.
- "impact": EXACTLY one of ["high", "medium", "low"] — estimated effect on the
  match score (prefer "high" for changes addressing missing required skills).
- "original_text": the exact snippet from the resume to change, or null when
  not applicable (e.g. adding a keyword or reordering).
- "suggested_text": the replacement/addition text, or null when not applicable.

Respond with ONLY a JSON object of the form:
{{"suggestions": [{{"category": "...", "description": "...", "impact": "...", "original_text": "...", "suggested_text": "..."}}]}}

If no improvements are warranted, respond with {{"suggestions": []}}.
Do not include any prose, explanation, or markdown fences.

TARGET JOB DESCRIPTION:
{jd_block}

MATCH BREAKDOWN:
{match_block}

CANDIDATE RESUME:
{resume_block}
"""


class ResumeEditorService:
    """Generate resume edit suggestions and tailored Word documents."""

    # -- Public API: suggestions -------------------------------------------

    async def generate_suggestions(
        self,
        match: MatchBreakdown,
        resume: ParsedResume,
        jd: ScrapedJD,
    ) -> list[EditSuggestion]:
        """Generate prioritised, categorised resume edit suggestions via LLM.

        Produces actionable suggestions to improve the alignment between the
        base resume and the job description (Requirement 5.1), each categorised
        as ``skills_to_add``, ``experience_rephrase``, ``keywords_to_include``,
        or ``sections_reorder`` (Requirement 5.2), and ordered by estimated
        impact so high-impact changes come first (Requirement 5.3). The prompt
        constrains the model to preserve factual accuracy — edits are limited to
        rephrasing, reordering, and keyword optimisation (Requirement 5.4).

        Any LLM/transport failure or unusable output degrades gracefully to an
        empty list rather than raising.

        Args:
            match: The computed match breakdown (drives prioritisation).
            resume: The user's parsed base resume.
            jd: The scraped, structured job description.

        Returns:
            A list of validated :class:`EditSuggestion` objects, sorted
            high-impact first (possibly empty).
        """
        try:
            raw_response = await self._invoke_llm(match, resume, jd)
        except Exception:
            # Any LLM/transport failure degrades gracefully to "no suggestions"
            # rather than surfacing an error, mirroring the other services.
            return []

        suggestions = self._parse_llm_response(raw_response)
        return self._sort_by_impact(suggestions)

    # -- Public API: tailored document -------------------------------------

    def generate_tailored_docx(
        self,
        base_resume_path: str,
        suggestions: list[EditSuggestion],
        *,
        parsed_resume: ParsedResume | None = None,
        base_file_type: str | None = None,
        output_dir: str | Path | None = None,
    ) -> str:
        """Apply suggestions to a copy of the base resume and return the path.

        Builds a new ``.docx`` by applying ``suggestions`` to a copy of the base
        resume's content (Requirement 6.1), preserving the original formatting,
        fonts, and layout as closely as possible (Requirement 6.2) and
        highlighting the modified sections so the user can identify what changed
        (Requirement 6.3). The base resume on disk is never modified — the
        result is always a new, separate file (Requirement 6.5).

        When the base resume was uploaded as a PDF (``base_file_type == "pdf"``,
        or the path does not end in ``.docx``), the parsed resume content is
        rendered into a fresh Word document before edits are applied
        (Requirement 6.6). In that case ``parsed_resume`` must be supplied.

        Args:
            base_resume_path: Filesystem path to the stored base resume.
            suggestions: The edit suggestions to apply.
            parsed_resume: The parsed resume content, required when the base
                resume is a PDF (or otherwise cannot be opened as ``.docx``).
            base_file_type: Optional explicit base file type ("pdf"/"docx");
                when omitted it is inferred from ``base_resume_path``.
            output_dir: Directory to write the generated file into. Defaults to
                the configured ``generated`` directory from settings.

        Returns:
            The filesystem path to the generated ``.docx`` file.

        Raises:
            ValueError: If the base resume is a PDF (or not a readable ``.docx``)
                and no ``parsed_resume`` was supplied to rebuild from.
        """
        document = self._load_or_build_document(
            base_resume_path, base_file_type, parsed_resume
        )

        changes = self._apply_edits_to_docx(document, suggestions)
        self._highlight_changes(document, changes)

        out_dir = self._resolve_output_dir(output_dir)
        out_dir.mkdir(parents=True, exist_ok=True)
        out_path = out_dir / f"tailored_resume_{uuid.uuid4().hex}.docx"
        document.save(str(out_path))
        return str(out_path)

    # -- Document loading / rebuilding -------------------------------------

    def _load_or_build_document(
        self,
        base_resume_path: str,
        base_file_type: str | None,
        parsed_resume: ParsedResume | None,
    ) -> Document:
        """Open the base ``.docx`` or rebuild one from parsed content.

        For a DOCX base, the file is opened directly so its formatting/fonts are
        preserved (Requirement 6.2). For a PDF base (Requirement 6.6) — or any
        file that cannot be opened as a Word document — a new document is built
        from ``parsed_resume``.
        """
        file_type = (base_file_type or "").strip().lower().lstrip(".")
        if not file_type:
            file_type = Path(base_resume_path or "").suffix.lower().lstrip(".")

        if file_type == "docx":
            try:
                return Document(base_resume_path)
            except Exception:
                # Fall through to rebuilding from parsed content if the DOCX is
                # unreadable and we have parsed data to fall back on.
                if parsed_resume is None:
                    raise

        # PDF (or unreadable DOCX): rebuild from parsed content.
        if parsed_resume is None:
            raise ValueError(
                "A parsed_resume is required to generate a tailored Word "
                "document from a non-DOCX (e.g. PDF) base resume."
            )
        return self._build_docx_from_parsed(parsed_resume)

    def _build_docx_from_parsed(self, parsed: ParsedResume) -> Document:
        """Render a :class:`ParsedResume` into a fresh, readable Word document.

        Produces a clean, conventionally-structured resume (contact header,
        Skills, Experience, Education, Certifications) that subsequent edits can
        be applied to. Used when the base resume was a PDF (Requirement 6.6).
        """
        document = Document()

        contact = parsed.contact
        if contact.name:
            heading = document.add_heading(contact.name, level=0)
            heading.alignment = 1  # centre
        contact_bits = [
            bit
            for bit in (contact.email, contact.phone, contact.location)
            if bit
        ]
        contact_bits.extend(contact.links or [])
        if contact_bits:
            para = document.add_paragraph(" | ".join(contact_bits))
            para.alignment = 1  # centre

        if parsed.skills:
            document.add_heading("Skills", level=1)
            document.add_paragraph(", ".join(parsed.skills))

        if parsed.experience:
            document.add_heading("Experience", level=1)
            for entry in parsed.experience:
                title_bits = [b for b in (entry.title, entry.company) if b]
                date_bits = [b for b in (entry.start_date, entry.end_date) if b]
                header_line = " — ".join(title_bits)
                if date_bits:
                    header_line = (
                        f"{header_line} ({' - '.join(date_bits)})"
                        if header_line
                        else " - ".join(date_bits)
                    )
                if header_line:
                    para = document.add_paragraph()
                    run = para.add_run(header_line)
                    run.bold = True
                if entry.description:
                    document.add_paragraph(entry.description)
                for highlight in entry.highlights:
                    document.add_paragraph(highlight, style="List Bullet")

        if parsed.education:
            document.add_heading("Education", level=1)
            for edu in parsed.education:
                edu_bits = [
                    b
                    for b in (edu.degree, edu.field_of_study, edu.institution)
                    if b
                ]
                date_bits = [b for b in (edu.start_date, edu.end_date) if b]
                line = ", ".join(edu_bits)
                if date_bits:
                    line = (
                        f"{line} ({' - '.join(date_bits)})"
                        if line
                        else " - ".join(date_bits)
                    )
                if line:
                    document.add_paragraph(line)

        if parsed.certifications:
            document.add_heading("Certifications", level=1)
            for cert in parsed.certifications:
                document.add_paragraph(cert, style="List Bullet")

        return document

    # -- Edit application ---------------------------------------------------

    def _apply_edits_to_docx(
        self, document: Document, suggestions: list[EditSuggestion]
    ) -> list[dict[str, Any]]:
        """Apply suggestions to ``document`` in place; return applied changes.

        Handles each suggestion category while preserving the surrounding
        document structure (Requirements 6.1, 6.2):

        * ``experience_rephrase`` / ``keywords_to_include`` with both
          ``original_text`` and ``suggested_text``: an in-place text replacement
          within the matching paragraph, preserving that paragraph's style.
        * ``skills_to_add`` / ``keywords_to_include`` without an original: the
          ``suggested_text`` is appended to the Skills section (or a new Skills
          section is created) so no existing content is lost.
        * ``sections_reorder`` and any suggestion lacking actionable text: a
          non-destructive annotation paragraph is appended describing the
          recommended change, so the user is informed without corrupting layout.

        Args:
            document: The Word document to modify in place.
            suggestions: The edit suggestions to apply.

        Returns:
            A list of change descriptors (each a dict with a ``"paragraph"`` and
            a ``"kind"``) identifying the paragraphs that were modified/added, so
            :meth:`_highlight_changes` can annotate them.
        """
        changes: list[dict[str, Any]] = []

        for suggestion in suggestions:
            original = (suggestion.original_text or "").strip()
            suggested = (suggestion.suggested_text or "").strip()

            # 1) In-place replacement when we have both sides of the edit.
            if original and suggested:
                replaced = self._replace_text_in_document(
                    document, original, suggested
                )
                if replaced is not None:
                    changes.append({"paragraph": replaced, "kind": "replaced"})
                    continue
                # If the original could not be found, fall through to appending.

            # 2) Additive content (skills / keywords) with text to add.
            if suggested and suggestion.category in {
                "skills_to_add",
                "keywords_to_include",
            }:
                para = self._append_to_skills(document, suggested)
                changes.append({"paragraph": para, "kind": "added"})
                continue

            # 3) Anything else: append a non-destructive annotation.
            note = self._format_annotation(suggestion)
            para = document.add_paragraph(note)
            changes.append({"paragraph": para, "kind": "note"})

        return changes

    def _replace_text_in_document(
        self, document: Document, original: str, suggested: str
    ):
        """Replace the first paragraph containing ``original`` with ``suggested``.

        Replacement is performed at the paragraph level (rewriting the
        paragraph's runs into a single run) so that the paragraph's *style*
        (and thus its place in the layout) is preserved even though inline
        run-level formatting within that paragraph is normalised. Matching is
        case-insensitive and whitespace-tolerant.

        Returns the modified paragraph, or ``None`` when no paragraph contains
        the original text.
        """
        needle = self._normalise_ws(original).lower()
        if not needle:
            return None

        for paragraph in document.paragraphs:
            haystack = self._normalise_ws(paragraph.text)
            if not haystack:
                continue
            if needle in haystack.lower():
                new_text = self._case_insensitive_replace(
                    haystack, original, suggested
                )
                self._set_paragraph_text(paragraph, new_text)
                return paragraph
        return None

    def _append_to_skills(self, document: Document, text: str):
        """Append ``text`` to the Skills section, creating it if necessary.

        Looks for a heading/paragraph that reads like "Skills"; appends the new
        text to the following content paragraph when present, otherwise creates
        a Skills heading and content paragraph. Returns the paragraph that was
        added or modified.
        """
        paragraphs = document.paragraphs
        for idx, paragraph in enumerate(paragraphs):
            if self._normalise_ws(paragraph.text).lower().rstrip(":") == "skills":
                # Append to the next non-empty paragraph if it looks like content.
                if idx + 1 < len(paragraphs):
                    content = paragraphs[idx + 1]
                    existing = content.text.strip()
                    if existing:
                        self._set_paragraph_text(
                            content, f"{existing}, {text}"
                        )
                    else:
                        self._set_paragraph_text(content, text)
                    return content
                # No content paragraph after the heading: add one.
                return document.add_paragraph(text)

        # No Skills section found: create one.
        document.add_heading("Skills", level=1)
        return document.add_paragraph(text)

    # -- Highlighting -------------------------------------------------------

    def _highlight_changes(
        self, document: Document, changes: list[dict[str, Any]]
    ) -> Document:
        """Highlight/annotate modified paragraphs so changes are identifiable.

        Applies a yellow highlight to every run of each changed paragraph
        (Requirement 6.3). Annotation paragraphs ("note" kind) are additionally
        italicised so they are visually distinct from resume content. The
        document is modified in place and also returned for convenience.
        """
        for change in changes:
            paragraph = change.get("paragraph")
            if paragraph is None:
                continue
            is_note = change.get("kind") == "note"
            runs = paragraph.runs or []
            if not runs:
                # Ensure there is at least one run to carry the highlight.
                runs = [paragraph.add_run(paragraph.text)]
            for run in runs:
                run.font.highlight_color = WD_COLOR_INDEX.YELLOW
                if is_note:
                    run.italic = True
        return document

    # -- LLM invocation (isolated for testability) --------------------------

    async def _invoke_llm(
        self, match: MatchBreakdown, resume: ParsedResume, jd: ScrapedJD
    ) -> str:
        """Invoke the configured chat model and return its raw text content.

        Isolated from parsing so that :meth:`_parse_llm_response` can be tested
        with canned responses and no live model.
        """
        model = get_chat_model()
        messages = [
            ("system", _SYSTEM_PROMPT),
            (
                "human",
                _PROMPT_TEMPLATE.format(
                    jd_block=self._format_jd_block(jd),
                    match_block=self._format_match_block(match),
                    resume_block=self._format_resume_block(resume),
                ),
            ),
        ]
        response = await model.ainvoke(messages)
        return self._content_to_text(getattr(response, "content", response))

    # -- Prompt context formatting -----------------------------------------

    @staticmethod
    def _format_jd_block(jd: ScrapedJD) -> str:
        """Render the salient JD fields into a compact prompt block."""
        parts = [
            f"Title: {jd.job_title}",
            f"Company: {jd.company_name}",
        ]
        if jd.experience_required:
            parts.append(f"Experience required: {jd.experience_required}")
        if jd.required_skills:
            parts.append(f"Required skills: {', '.join(jd.required_skills)}")
        if jd.preferred_skills:
            parts.append(f"Preferred skills: {', '.join(jd.preferred_skills)}")
        if jd.description_body:
            parts.append(f"Description:\n{jd.description_body}")
        return "\n".join(parts)

    @staticmethod
    def _format_match_block(match: MatchBreakdown) -> str:
        """Render the match breakdown into a compact prompt block."""
        parts = [
            f"Overall score: {match.overall_score} ({match.category})",
            f"Skills score: {match.skills_score}",
            f"Experience score: {match.experience_score}",
            f"Education score: {match.education_score}",
        ]
        if match.matched_skills:
            parts.append(f"Matched skills: {', '.join(match.matched_skills)}")
        if match.missing_skills:
            parts.append(f"Missing skills: {', '.join(match.missing_skills)}")
        if match.missing_experience_keywords:
            parts.append(
                "Missing experience keywords: "
                + ", ".join(match.missing_experience_keywords)
            )
        return "\n".join(parts)

    @staticmethod
    def _format_resume_block(resume: ParsedResume) -> str:
        """Render the parsed resume into a compact prompt block.

        Prefers the structured sections; falls back to raw text when the
        structured sections are empty.
        """
        parts: list[str] = []
        if resume.skills:
            parts.append(f"Skills: {', '.join(resume.skills)}")
        if resume.experience:
            parts.append("Experience:")
            for entry in resume.experience:
                header = " — ".join(
                    b for b in (entry.title, entry.company) if b
                )
                if header:
                    parts.append(f"- {header}")
                if entry.description:
                    parts.append(f"  {entry.description}")
                for highlight in entry.highlights:
                    parts.append(f"  * {highlight}")
        if resume.education:
            parts.append("Education:")
            for edu in resume.education:
                line = ", ".join(
                    b
                    for b in (edu.degree, edu.field_of_study, edu.institution)
                    if b
                )
                if line:
                    parts.append(f"- {line}")
        if resume.certifications:
            parts.append(f"Certifications: {', '.join(resume.certifications)}")

        if not parts:
            return resume.raw_text or "(no resume content available)"
        return "\n".join(parts)

    # -- Parsing / normalisation --------------------------------------------

    def _parse_llm_response(self, raw_response: str) -> list[EditSuggestion]:
        """Parse and normalise the LLM response into valid edit suggestions.

        Extracts the JSON payload (tolerating surrounding prose or markdown
        code fences), then normalises each entry's category and impact to the
        schema's allowed values, dropping entries without a usable description.
        """
        payload = self._extract_json(raw_response)
        if not isinstance(payload, dict):
            return []

        raw_items = payload.get("suggestions")
        if not isinstance(raw_items, list):
            return []

        suggestions: list[EditSuggestion] = []
        for entry in raw_items:
            suggestion = self._coerce_suggestion(entry)
            if suggestion is not None:
                suggestions.append(suggestion)
        return suggestions

    def _coerce_suggestion(self, entry: Any) -> EditSuggestion | None:
        """Coerce one raw LLM entry into a valid :class:`EditSuggestion`.

        Returns ``None`` when the entry is not a mapping or has no usable
        description. Unknown category/impact values are coerced to safe
        defaults rather than dropping the entry.
        """
        if not isinstance(entry, dict):
            return None

        description = entry.get("description")
        if not isinstance(description, str) or not description.strip():
            return None

        return EditSuggestion(
            category=self._normalise_category(entry.get("category")),
            description=description.strip(),
            impact=self._normalise_impact(entry.get("impact")),
            original_text=self._coerce_optional_str(entry.get("original_text")),
            suggested_text=self._coerce_optional_str(entry.get("suggested_text")),
        )

    @staticmethod
    def _normalise_category(value: Any) -> SuggestionCategory:
        """Map a free-form category value onto an allowed category Literal."""
        if isinstance(value, str):
            cleaned = value.strip().lower()
            if cleaned in _VALID_CATEGORIES:
                return cleaned  # type: ignore[return-value]
            collapsed = re.sub(r"[\s\-]+", "_", cleaned)
            if collapsed in _VALID_CATEGORIES:
                return collapsed  # type: ignore[return-value]
            if cleaned in _CATEGORY_ALIASES:
                return _CATEGORY_ALIASES[cleaned]
        # Default to keyword inclusion: a safe, non-destructive category.
        return "keywords_to_include"

    @staticmethod
    def _normalise_impact(value: Any) -> Impact:
        """Map a free-form impact value onto an allowed impact Literal."""
        if isinstance(value, str):
            cleaned = value.strip().lower()
            if cleaned in _VALID_IMPACTS:
                return cleaned  # type: ignore[return-value]
            if cleaned in _IMPACT_ALIASES:
                return _IMPACT_ALIASES[cleaned]
        return _DEFAULT_IMPACT

    @staticmethod
    def _coerce_optional_str(value: Any) -> str | None:
        """Coerce a scalar value into a trimmed string, or ``None``.

        Empty / whitespace-only strings and JSON ``null`` become ``None``.
        """
        if isinstance(value, str):
            cleaned = value.strip()
            return cleaned or None
        return None

    @classmethod
    def _sort_by_impact(
        cls, suggestions: list[EditSuggestion]
    ) -> list[EditSuggestion]:
        """Return suggestions sorted high-impact first (Requirement 5.3).

        Uses a stable sort so that, within the same impact level, the LLM's
        original ordering is preserved.
        """
        return sorted(
            suggestions,
            key=lambda s: _IMPACT_ORDER.get(s.impact, _IMPACT_ORDER["medium"]),
        )

    # -- Text / docx helpers ------------------------------------------------

    @staticmethod
    def _format_annotation(suggestion: EditSuggestion) -> str:
        """Build a readable annotation line for a non-applicable suggestion."""
        label = suggestion.category.replace("_", " ").title()
        text = f"[Suggestion — {label}] {suggestion.description}"
        if suggestion.suggested_text:
            text = f"{text} (Suggested: {suggestion.suggested_text})"
        return text

    @staticmethod
    def _set_paragraph_text(paragraph, text: str) -> None:
        """Replace a paragraph's text with ``text`` while keeping its style.

        Clears the paragraph's existing runs and writes a single new run, so the
        paragraph-level style (heading/bullet/normal) and its position in the
        document are preserved even though inline run formatting is normalised.
        """
        # Remove all existing runs from the paragraph's XML.
        for run in list(paragraph.runs):
            run._element.getparent().remove(run._element)
        paragraph.add_run(text)

    @staticmethod
    def _normalise_ws(text: str) -> str:
        """Collapse runs of whitespace into single spaces and trim ends."""
        return re.sub(r"\s+", " ", text or "").strip()

    @staticmethod
    def _case_insensitive_replace(
        haystack: str, needle: str, replacement: str
    ) -> str:
        """Replace occurrences of ``needle`` in ``haystack`` ignoring case.

        Whitespace within ``needle`` is treated flexibly (any run of whitespace
        matches) so that line-wrapped text in the resume still matches.
        """
        pattern = re.compile(
            r"\s+".join(re.escape(part) for part in needle.split()),
            re.IGNORECASE,
        )
        replaced = pattern.sub(lambda _m: replacement, haystack)
        # If flexible matching found nothing (e.g. needle had no word parts),
        # fall back to a simple case-insensitive substring replace.
        if replaced == haystack and needle:
            replaced = re.sub(
                re.escape(needle), replacement, haystack, flags=re.IGNORECASE
            )
        return replaced

    @staticmethod
    def _resolve_output_dir(output_dir: str | Path | None) -> Path:
        """Resolve the directory to write generated documents into.

        Defaults to the configured ``generated`` directory from settings when
        not overridden. Imported lazily to keep this module importable without
        a configured environment during unit tests that pass ``output_dir``.
        """
        if output_dir is not None:
            return Path(output_dir)
        from config import settings

        return Path(settings.generated_dir)

    # -- JSON / content extraction (shared pattern) -------------------------

    @staticmethod
    def _extract_json(raw_response: str) -> dict[str, Any] | None:
        """Best-effort extraction of a JSON object from an LLM response.

        Handles responses that are pure JSON, wrapped in markdown code fences,
        or embedded in surrounding prose. Returns ``None`` when no JSON object
        can be parsed.
        """
        if not raw_response or not raw_response.strip():
            return None

        text = raw_response.strip()

        # Strip markdown code fences such as ```json ... ``` if present.
        fence = re.match(r"^```(?:json)?\s*(.*?)\s*```$", text, re.DOTALL)
        if fence:
            text = fence.group(1).strip()

        # First, try to parse the whole thing as JSON.
        try:
            parsed = json.loads(text)
            return parsed if isinstance(parsed, dict) else None
        except (ValueError, TypeError):
            pass

        # Otherwise, locate the first balanced {...} object in the text.
        start = text.find("{")
        while start != -1:
            depth = 0
            for idx in range(start, len(text)):
                char = text[idx]
                if char == "{":
                    depth += 1
                elif char == "}":
                    depth -= 1
                    if depth == 0:
                        candidate = text[start : idx + 1]
                        try:
                            parsed = json.loads(candidate)
                            return parsed if isinstance(parsed, dict) else None
                        except (ValueError, TypeError):
                            break
            start = text.find("{", start + 1)
        return None

    @staticmethod
    def _content_to_text(content: Any) -> str:
        """Normalise LangChain message content into a plain string.

        LangChain chat models may return a string or a list of content blocks
        (e.g. ``[{"type": "text", "text": "..."}]``). This flattens either form
        into a single string.
        """
        if isinstance(content, str):
            return content
        if isinstance(content, list):
            parts: list[str] = []
            for block in content:
                if isinstance(block, str):
                    parts.append(block)
                elif isinstance(block, dict):
                    text = block.get("text")
                    if isinstance(text, str):
                        parts.append(text)
            return "".join(parts)
        return str(content) if content is not None else ""
